-- 家长投诉表
DROP TABLE IF EXISTS `xfpt_parent_complaint`;
CREATE TABLE `xfpt_parent_complaint` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `user_id` varchar(100) DEFAULT NULL COMMENT '家长ID',
  `user_name` varchar(100) DEFAULT NULL COMMENT '家长姓名',
  `dept_id` varchar(100) DEFAULT NULL COMMENT '学校ID',
  `dept_name` varchar(100) DEFAULT NULL COMMENT '学校名称',
  `order_id` bigint DEFAULT NULL COMMENT '订单ID',
  `order_no` varchar(100) DEFAULT NULL COMMENT '订单号',
  `order_item_id` bigint DEFAULT NULL COMMENT '订单明细ID',
  `goods_id` bigint DEFAULT NULL COMMENT '商品ID',
  `goods_name` varchar(255) DEFAULT NULL COMMENT '商品名称',
  `supplier_id` bigint DEFAULT NULL COMMENT '供应商ID',
  `supplier_name` varchar(255) DEFAULT NULL COMMENT '供应商名称',
  `complaint_type` varchar(100) DEFAULT NULL COMMENT '投诉类型',
  `complaint_reason` text COMMENT '投诉原因',
  `complaint_images` text COMMENT '投诉图片，多个逗号分隔',
  `contact_phone` varchar(100) DEFAULT NULL COMMENT '联系电话',
  `status` varchar(20) DEFAULT '0' COMMENT '处理状态：0处理中，1已处理，2已关闭',
  `handle_content` text COMMENT '处理结果',
  `handle_by` varchar(100) DEFAULT NULL COMMENT '处理人',
  `handle_time` datetime DEFAULT NULL COMMENT '处理时间',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `del_flag` varchar(1) DEFAULT '0' COMMENT '删除标志（0存在 1删除）',
  `create_by` varchar(100) DEFAULT NULL COMMENT '创建人',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_by` varchar(100) DEFAULT NULL COMMENT '更新人',
  `update_time` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  KEY `idx_parent_complaint_user_id` (`user_id`),
  KEY `idx_parent_complaint_order_id` (`order_id`),
  KEY `idx_parent_complaint_order_no` (`order_no`),
  KEY `idx_parent_complaint_supplier_id` (`supplier_id`),
  KEY `idx_parent_complaint_status` (`status`),
  KEY `idx_parent_complaint_create_time` (`create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='家长投诉表';
