    @Override
    public boolean isPwdExpire(String username) {
        String username1 = SecurityUtils.getUsername();
        System.out.println(username1);
        SysUser sysUser = selectUserByUserName(username1);
        Date pwdTime = sysUser.getPwdtime();
        if(pwdTime==null){
            return true;
        }
        LocalDate pwdDate = pwdTime.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
        // 获取当前日期
        LocalDate currentDate = LocalDate.now();
        // 计算日期差异
        Period period = Period.between(pwdDate, currentDate);
        String blackStr = Convert.toStr(redisService.getCacheObject("sys_config:pwd.update"));
        // 检查月份差异是否大于等于三个月
        if (period.toTotalMonths() >= Long.parseLong(blackStr)) {
            return true;
        }
        if(sysUser.getPwdtime()==null){
            return true;
        }


        return false;
    }


